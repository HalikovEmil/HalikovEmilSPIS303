using System;
using System.Collections.Generic;
using System.Text;

namespace Leason1
{
    public class Math
    {
        public double Sum(int num1, int num2)
        {
            return num1 + num2;
        }

        public double Sub(int num1, int num2)
        {
            return num1 - num2;
        }

        public double Mult(int num1, int num2)
        {
            return num1 * num2;
        }

        public double Div(int num1, int num2)
        {
            return num1 / num2;
        }
    }
}
